-- ==============================================================================
-- MOTRIK - Esquema de Base de Datos para Supabase
-- ==============================================================================
-- Este script crea todas las tablas, relaciones, políticas RLS y datos iniciales (seed)
-- necesarios para conectar el frontend de Motrik a Supabase.
-- Puedes ejecutarlo directamente en el SQL Editor del dashboard de Supabase.
-- ==============================================================================

-- 1. TABLA: usuarios
CREATE TABLE IF NOT EXISTS public.usuarios (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre TEXT NOT NULL,
  correo TEXT UNIQUE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. TABLA: vehiculos
CREATE TABLE IF NOT EXISTS public.vehiculos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id UUID REFERENCES public.usuarios(id) ON DELETE SET NULL,
  marca TEXT NOT NULL,
  modelo TEXT NOT NULL,
  ano INTEGER NOT NULL,
  placa TEXT NOT NULL UNIQUE,
  kilometraje INTEGER DEFAULT 0,
  motor TEXT DEFAULT '2.0L',
  combustible TEXT DEFAULT 'Gasolina',
  transmision TEXT DEFAULT 'Automática',
  color TEXT DEFAULT 'Plata',
  imagen_url TEXT,
  soat_vencimiento TEXT,
  tecno_vencimiento TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. TABLA: repuestos
CREATE TABLE IF NOT EXISTS public.repuestos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  marca TEXT NOT NULL,
  categoria_vehiculo TEXT NOT NULL,
  precio NUMERIC NOT NULL,
  precio_anterior NUMERIC,
  calificacion NUMERIC(2,1) DEFAULT 4.8,
  resenas_count INTEGER DEFAULT 12,
  stock INTEGER DEFAULT 10,
  imagen_url TEXT,
  imagenes TEXT[] DEFAULT ARRAY[]::TEXT[],
  compatibilidad TEXT DEFAULT 'Universal',
  especificaciones JSONB DEFAULT '{}'::JSONB,
  envio_gratis BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 4. TABLA: registros_bitacora
CREATE TABLE IF NOT EXISTS public.registros_bitacora (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id BIGINT REFERENCES public.vehiculos(id) ON DELETE CASCADE,
  fecha TIMESTAMPTZ DEFAULT now(),
  descripcion_cambio TEXT,
  pieza_actualizada TEXT,
  repuesto_id BIGINT REFERENCES public.repuestos(id) ON DELETE SET NULL,
  titulo TEXT,
  descripcion TEXT,
  kilometraje INTEGER DEFAULT 0,
  taller TEXT,
  costo NUMERIC DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 5. TABLA: mecanicos (Directorio de Talleres)
CREATE TABLE IF NOT EXISTS public.mecanicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id UUID REFERENCES public.usuarios(id) ON DELETE SET NULL,
  especialidad TEXT NOT NULL,
  ubicacion TEXT NOT NULL,
  calificacion_promedio NUMERIC(2,1) DEFAULT 4.9,
  foto_url TEXT,
  telefono TEXT,
  horario TEXT DEFAULT 'Lun–Sáb 7:30–18:00',
  anos_experiencia INTEGER DEFAULT 10,
  descripcion TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 6. TABLA: valoraciones (Reseñas con restricción explícita para PostgREST)
-- IMPORTANTE: La restricción 'valoraciones_cliente_id_fkey' es requerida por la consulta
-- de src/app/directorio/page.tsx: cliente:usuarios!valoraciones_cliente_id_fkey(nombre)
CREATE TABLE IF NOT EXISTS public.valoraciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mecanico_id BIGINT REFERENCES public.mecanicos(id) ON DELETE CASCADE,
  cliente_id UUID,
  puntuacion NUMERIC(2,1) NOT NULL DEFAULT 5.0,
  comentario TEXT,
  fecha TIMESTAMPTZ DEFAULT now(),
  CONSTRAINT valoraciones_cliente_id_fkey FOREIGN KEY (cliente_id) REFERENCES public.usuarios(id) ON DELETE SET NULL
);

-- ==============================================================================
-- POLÍTICAS DE ACCESO (Row Level Security - RLS)
-- ==============================================================================
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vehiculos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.repuestos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registros_bitacora ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mecanicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.valoraciones ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura pública para catálogo y directorio (Acceso anónimo y autenticado)
CREATE POLICY "Lectura pública de usuarios" ON public.usuarios FOR SELECT USING (true);
CREATE POLICY "Lectura pública de vehiculos" ON public.vehiculos FOR SELECT USING (true);
CREATE POLICY "Lectura pública de repuestos" ON public.repuestos FOR SELECT USING (true);
CREATE POLICY "Lectura pública de bitacora" ON public.registros_bitacora FOR SELECT USING (true);
CREATE POLICY "Lectura pública de mecanicos" ON public.mecanicos FOR SELECT USING (true);
CREATE POLICY "Lectura pública de valoraciones" ON public.valoraciones FOR SELECT USING (true);

-- Permisos de escritura para el MVP
CREATE POLICY "Permitir insertar mantenimientos" ON public.registros_bitacora FOR INSERT WITH CHECK (true);
CREATE POLICY "Permitir actualizar vehiculos" ON public.vehiculos FOR UPDATE USING (true);

